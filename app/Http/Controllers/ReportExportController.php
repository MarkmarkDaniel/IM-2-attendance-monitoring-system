<?php

namespace App\Http\Controllers;

use App\Services\ReportService;
use Carbon\Carbon;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\StreamedResponse;
use Barryvdh\DomPDF\Facade\Pdf;
use Symfony\Component\HttpFoundation\Response;

class ReportExportController extends Controller
{
    public function __construct(private ReportService $reports)
    {
    }

    /**
     * One CSV endpoint for every report type.
     * ?report=daily|student|class|department|monthly
     */
    public function csv(Request $request): StreamedResponse
    {
        $type = $request->query('report', 'daily');

        $filters = [
            'date'          => $request->query('date'),
            'date_from'     => $request->query('date_from'),
            'date_to'       => $request->query('date_to'),
            'class_id'      => $request->query('class_id'),
            'student_id'    => $request->query('student_id'),
            'subject_id'    => $request->query('subject_id'),
            'department_id' => $request->query('department_id'),
            'instructor_id' => $request->query('instructor_id'),
            'status'        => $request->query('status'),
        ];

        $instructorId = $request->user()->isAdmin()
            ? null
            : $request->user()->instructor?->id;

        abort_if(! $request->user()->isAdmin() && ! $instructorId, 403);

        [$title, $headers, $rows] = match ($type) {
            'student'    => $this->studentRows($filters, $instructorId),
            'class'      => $this->classRows($filters, $instructorId),
            'department' => $this->departmentRows($filters, $instructorId),
            'monthly'    => $this->monthlyRows($filters, $instructorId),
            default      => $this->dailyRows($filters, $instructorId),
        };

        $filename = str($title)->slug('_') . '_' . now()->format('Ymd_His') . '.csv';

        return response()->streamDownload(
            function () use ($title, $filters, $headers, $rows, $request) {
                $handle = fopen('php://output', 'w');

                // Excel needs this BOM to read UTF-8 correctly
                fwrite($handle, "\xEF\xBB\xBF");

                // ---------- Report header block ----------
                fputcsv($handle, [config('app.name')]);
                fputcsv($handle, [$title]);
                fputcsv($handle, ['Generated', now()->format('F j, Y g:i A')]);
                fputcsv($handle, ['Generated By', $request->user()->name]);
                fputcsv($handle, []);

                // ---------- Applied filters ----------
                fputcsv($handle, ['APPLIED FILTERS']);

                $applied = array_filter($filters, fn ($value) => ! blank($value));

                if (empty($applied)) {
                    fputcsv($handle, ['None', 'All records']);
                } else {
                    foreach ($applied as $key => $value) {
                        fputcsv($handle, [str($key)->replace('_', ' ')->title(), $value]);
                    }
                }

                fputcsv($handle, []);

                // ---------- Data ----------
                fputcsv($handle, $headers);

                foreach ($rows as $row) {
                    fputcsv($handle, $row);
                }

                fclose($handle);
            },
            $filename,
            [
                'Content-Type'        => 'text/csv; charset=UTF-8',
                'Content-Disposition' => 'attachment; filename="' . $filename . '"',
            ]
        );
    }

        /**
     * PDF version of any report, using the same row builders as the CSV.
     */
    public function pdf(Request $request): Response
    {
        $type = $request->query('report', 'daily');

        $filters = [
            'date'          => $request->query('date'),
            'date_from'     => $request->query('date_from'),
            'date_to'       => $request->query('date_to'),
            'class_id'      => $request->query('class_id'),
            'student_id'    => $request->query('student_id'),
            'subject_id'    => $request->query('subject_id'),
            'department_id' => $request->query('department_id'),
            'instructor_id' => $request->query('instructor_id'),
            'status'        => $request->query('status'),
        ];

        $instructorId = $request->user()->isAdmin()
            ? null
            : $request->user()->instructor?->id;

        abort_if(! $request->user()->isAdmin() && ! $instructorId, 403);

        [$title, $headers, $rows] = match ($type) {
            'student'    => $this->studentRows($filters, $instructorId),
            'class'      => $this->classRows($filters, $instructorId),
            'department' => $this->departmentRows($filters, $instructorId),
            'monthly'    => $this->monthlyRows($filters, $instructorId),
            default      => $this->dailyRows($filters, $instructorId),
        };

        $summary = $this->reports->summarize(
            $this->reports->baseQuery($filters, $instructorId)
        );

        $pdf = Pdf::loadView('reports.pdf', [
            'title'       => $title,
            'headers'     => $headers,
            'rows'        => $rows,
            'summary'     => $summary,
            'filters'     => array_filter($filters, fn ($v) => ! blank($v)),
            'generatedBy' => $request->user()->name,
        ])->setPaper('a4', 'landscape');

        $filename = str($title)->slug('_') . '_' . now()->format('Ymd_His') . '.pdf';

        return $pdf->download($filename);
    }

    /* ==================================================================
     | Row builders
     ================================================================== */

    private function dailyRows(array $filters, ?int $instructorId): array
    {
        $records = $this->reports->baseQuery($filters, $instructorId)
            ->orderBy('attendance_date', 'desc')
            ->get();

        $rows = $records->map(fn ($r) => [
            $r->attendance_date->format('Y-m-d'),
            $r->student->student_number,
            $r->student->formal_name,
            $r->student->department->department_code,
            $r->classModel->subject->subject_code,
            $r->classModel->section,
            $r->time_in ? Carbon::parse($r->time_in)->format('g:i A') : '',
            $r->status,
            $r->remarks ?? '',
        ])->all();

        // Summary block at the bottom
        $summary = $this->reports->summarize(
            $this->reports->baseQuery($filters, $instructorId)
        );

        $rows[] = [];
        $rows[] = ['SUMMARY'];
        $rows[] = ['Total Records',    $summary['total']];
        $rows[] = ['Present',          $summary['present']];
        $rows[] = ['Late',             $summary['late']];
        $rows[] = ['Absent',           $summary['absent']];
        $rows[] = ['Attendance Rate',  $summary['rate'] . '%'];

        return [
            'Daily Attendance Report',
            ['Date', 'Student Number', 'Student Name', 'Department',
             'Subject', 'Section', 'Time In', 'Status', 'Remarks'],
            $rows,
        ];
    }

    private function studentRows(array $filters, ?int $instructorId): array
    {
        $records = $this->reports->baseQuery($filters, $instructorId)
            ->orderBy('attendance_date', 'desc')
            ->get();

        $rows = $records->map(fn ($r) => [
            $r->attendance_date->format('Y-m-d'),
            $r->classModel->subject->subject_code,
            $r->classModel->subject->subject_name,
            $r->classModel->section,
            $r->time_in ? Carbon::parse($r->time_in)->format('g:i A') : '',
            $r->status,
            $r->remarks ?? '',
        ])->all();

        $summary = $this->reports->summarize(
            $this->reports->baseQuery($filters, $instructorId)
        );

        $rows[] = [];
        $rows[] = ['SUMMARY'];
        $rows[] = ['Total Sessions',   $summary['total']];
        $rows[] = ['Present',          $summary['present']];
        $rows[] = ['Late',             $summary['late']];
        $rows[] = ['Absent',           $summary['absent']];
        $rows[] = ['Attendance Rate',  $summary['rate'] . '%'];

        return [
            'Student Attendance Report',
            ['Date', 'Subject Code', 'Subject Name', 'Section', 'Time In', 'Status', 'Remarks'],
            $rows,
        ];
    }

    private function classRows(array $filters, ?int $instructorId): array
    {
        $rows = $this->reports->perClass($filters, $instructorId)
            ->map(fn ($r) => [
                $r->subject_code,
                $r->subject_name,
                $r->section,
                $r->instructor_name,
                $r->student_count,
                $r->session_count,
                $r->present_count,
                $r->late_count,
                $r->absent_count,
                $r->attendance_rate . '%',
            ])->all();

        return [
            'Class Attendance Report',
            ['Subject Code', 'Subject Name', 'Section', 'Instructor',
             'Students', 'Sessions', 'Present', 'Late', 'Absent', 'Attendance Rate'],
            $rows,
        ];
    }

    private function departmentRows(array $filters, ?int $instructorId): array
    {
        $rows = $this->reports->perDepartment($filters, $instructorId)
            ->map(fn ($r) => [
                $r->department_code,
                $r->department_name,
                $r->student_count,
                $r->total_count,
                $r->present_count,
                $r->late_count,
                $r->absent_count,
                $r->attendance_rate . '%',
            ])->all();

        return [
            'Department Attendance Report',
            ['Code', 'Department Name', 'Students', 'Total Records',
             'Present', 'Late', 'Absent', 'Attendance Rate'],
            $rows,
        ];
    }

    private function monthlyRows(array $filters, ?int $instructorId): array
    {
        $rows = $this->reports->perDate($filters, $instructorId)
            ->map(fn ($r) => [
                Carbon::parse($r->attendance_date)->format('Y-m-d'),
                Carbon::parse($r->attendance_date)->format('l'),
                $r->total_count,
                $r->present_count,
                $r->late_count,
                $r->absent_count,
                $r->attendance_rate . '%',
            ])->all();

        return [
            'Monthly Attendance Report',
            ['Date', 'Day', 'Total Records', 'Present', 'Late', 'Absent', 'Attendance Rate'],
            $rows,
        ];
    }
}
